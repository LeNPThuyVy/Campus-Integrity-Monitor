<#
.SYNOPSIS
  Tải PHP 8.3 (NTS x64) chính thức và Microsoft Drivers for PHP for SQL Server (pdo_sqlsrv)
  vào thư mục tools\php của repository. Không cài vào hệ thống, không sửa PATH.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\setup-php-windows.ps1
  powershell -ExecutionPolicy Bypass -File scripts\setup-php-windows.ps1 -PhpVersion 8.3.35 -InstallDir D:\tools\php

.NOTES
  - Nguồn: https://windows.php.net (PHP) và https://github.com/microsoft/msphpsql/releases (driver).
  - PHP 8.3 cần Microsoft Visual C++ Redistributable 2015-2022 (x64).
  - Nếu dùng XAMPP/IIS sẵn có, chỉ cần chép php_pdo_sqlsrv_83_nts_x64.dll (hoặc _ts_ cho Apache)
    vào thư mục ext và thêm "extension=php_pdo_sqlsrv_83_nts_x64.dll" vào php.ini.
#>
param(
    [string]$PhpVersion = "8.3.35",
    [string]$DriverVersion = "5.13.3",
    [string]$InstallDir = (Join-Path (Split-Path -Parent $PSScriptRoot) "tools\php")
)

$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$phpExe = Join-Path $InstallDir "php.exe"
if (Test-Path $phpExe) {
    Write-Host "PHP đã có tại $InstallDir. Xóa thư mục này nếu muốn cài lại." -ForegroundColor Yellow
    & $phpExe -v
    exit 0
}

$work = Join-Path ([IO.Path]::GetTempPath()) ("cim-php-" + [Guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Force -Path $work | Out-Null
try {
    $zipName = "php-$PhpVersion-nts-Win32-vs16-x64.zip"
    $phpZip = Join-Path $work $zipName
    $downloaded = $false
    foreach ($base in @("https://windows.php.net/downloads/releases/", "https://windows.php.net/downloads/releases/archives/")) {
        try {
            Write-Host "Tải $base$zipName ..."
            Invoke-WebRequest -Uri ($base + $zipName) -OutFile $phpZip -UseBasicParsing
            $downloaded = $true
            break
        } catch {
            Write-Host "  Không có tại $base" -ForegroundColor DarkYellow
        }
    }
    if (-not $downloaded) { throw "Không tải được $zipName. Kiểm tra số phiên bản tại https://windows.php.net/download/" }

    $driverZip = Join-Path $work "msphpsql.zip"
    $driverUrl = "https://github.com/microsoft/msphpsql/releases/download/v$DriverVersion/Windows_${DriverVersion}RTW.zip"
    Write-Host "Tải $driverUrl ..."
    Invoke-WebRequest -Uri $driverUrl -OutFile $driverZip -UseBasicParsing

    New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
    Expand-Archive -Path $phpZip -DestinationPath $InstallDir -Force
    $driverDir = Join-Path $work "driver"
    Expand-Archive -Path $driverZip -DestinationPath $driverDir -Force

    $minor = ($PhpVersion.Split(".")[0..1] -join "")
    $dllName = "php_pdo_sqlsrv_${minor}_nts_x64.dll"
    $dll = Get-ChildItem -Path $driverDir -Recurse -Filter $dllName | Select-Object -First 1
    if (-not $dll) { throw "Không tìm thấy $dllName trong gói driver $DriverVersion." }
    Copy-Item $dll.FullName (Join-Path $InstallDir "ext\$dllName") -Force

    $ini = @"
; Generated by scripts\setup-php-windows.ps1 for Campus Integrity Monitor
extension_dir = "ext"
extension=mbstring
extension=fileinfo
extension=openssl
extension=zip
extension=$dllName
allow_url_fopen = On
memory_limit = 512M
upload_max_filesize = 20M
post_max_size = 25M
display_errors = Off
log_errors = On
error_reporting = E_ALL
date.timezone = Asia/Ho_Chi_Minh
session.cookie_httponly = 1
session.use_strict_mode = 1
"@
    Set-Content -Path (Join-Path $InstallDir "php.ini") -Value $ini -Encoding ASCII

    & $phpExe -v
    if ($LASTEXITCODE -ne 0) { throw "php.exe không chạy được. Cài Microsoft Visual C++ Redistributable 2015-2022 (x64) rồi thử lại." }
    $drivers = & $phpExe -r "echo implode(',', PDO::getAvailableDrivers());"
    if ($drivers -notmatch "sqlsrv") { throw "pdo_sqlsrv chưa nạp được (PDO drivers: $drivers)." }
    Write-Host "Hoàn tất: PHP $PhpVersion + pdo_sqlsrv $DriverVersion tại $InstallDir" -ForegroundColor Green
} finally {
    Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue
}
