/*
  Rollback migration 008. Không đưa ANH_KHOA về NOT NULL nếu đã có dòng NULL (sẽ mất dữ liệu).
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO

BEGIN TRY
    BEGIN TRANSACTION;

    IF COL_LENGTH(N'dbo.CAMERA', N'KHOA_THIET_BI_HASH') IS NOT NULL
        ALTER TABLE dbo.CAMERA DROP COLUMN KHOA_THIET_BI_HASH;

    -- Chỉ xóa cột do 008 thêm mới (nhận biết qua default constraint 008 tạo); cột đổi tên từ
    -- PHIEN_BAN_TOKEN/SO_LAN_SAI của migration 001 vẫn giữ. Không hoàn tác việc đổi tên cột TAIKHOAN
    -- vì API và Laravel hiện tại chỉ hiểu tên mới.
    IF OBJECT_ID(N'dbo.DF_TAIKHOAN_TOKEN_VERSION', N'D') IS NOT NULL
    BEGIN
        ALTER TABLE dbo.TAIKHOAN DROP CONSTRAINT DF_TAIKHOAN_TOKEN_VERSION;
        ALTER TABLE dbo.TAIKHOAN DROP COLUMN TOKEN_VERSION;
    END;
    IF OBJECT_ID(N'dbo.DF_TAIKHOAN_FAILED_ATTEMPTS', N'D') IS NOT NULL
    BEGIN
        ALTER TABLE dbo.TAIKHOAN DROP CONSTRAINT DF_TAIKHOAN_FAILED_ATTEMPTS;
        ALTER TABLE dbo.TAIKHOAN DROP COLUMN FAILED_ATTEMPTS;
    END;

    IF OBJECT_ID(N'dbo.PK_PHAT_HIEN_VIPHAM', N'PK') IS NOT NULL
        EXEC sp_rename N'dbo.PK_PHAT_HIEN_VIPHAM', N'PK_BAN_GHI_VIPHAM', N'OBJECT';
    IF OBJECT_ID(N'dbo.FK_PHAT_HIEN_VIPHAM_LOI', N'F') IS NOT NULL
        EXEC sp_rename N'dbo.FK_PHAT_HIEN_VIPHAM_LOI', N'FK_BAN_GHI_VIPHAM_LOI', N'OBJECT';
    IF OBJECT_ID(N'dbo.UQ_PHAT_HIEN_VIPHAM_MA_SU_KIEN', N'UQ') IS NOT NULL
        EXEC sp_rename N'dbo.UQ_PHAT_HIEN_VIPHAM_MA_SU_KIEN', N'UQ_BAN_GHI_VIPHAM_MA_SU_KIEN', N'OBJECT';
    IF OBJECT_ID(N'dbo.FK_ANH_VIPHAM_PHAT_HIEN', N'F') IS NOT NULL
        EXEC sp_rename N'dbo.FK_ANH_VIPHAM_PHAT_HIEN', N'FK_ANH_VIPHAM_BAN_GHI', N'OBJECT';
    IF OBJECT_ID(N'dbo.UQ_ANH_VIPHAM_PHAT_HIEN', N'UQ') IS NOT NULL
        EXEC sp_rename N'dbo.UQ_ANH_VIPHAM_PHAT_HIEN', N'UQ_ANH_VIPHAM_BAN_GHI', N'OBJECT';

    IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_ANH_VIPHAM_CAMERA' AND object_id = OBJECT_ID(N'dbo.ANH_VIPHAM'))
        DROP INDEX IX_ANH_VIPHAM_CAMERA ON dbo.ANH_VIPHAM;

    IF NOT EXISTS (SELECT 1 FROM dbo.ANH_VIPHAM WHERE ANH_KHOA IS NULL)
    BEGIN
        IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_ANH_VIPHAM_THOI_GIAN_HET_HAN' AND object_id = OBJECT_ID(N'dbo.ANH_VIPHAM'))
            DROP INDEX IX_ANH_VIPHAM_THOI_GIAN_HET_HAN ON dbo.ANH_VIPHAM;
        ALTER TABLE dbo.ANH_VIPHAM ALTER COLUMN ANH_KHOA NVARCHAR(260) NOT NULL;
        EXEC sp_executesql N'CREATE NONCLUSTERED INDEX IX_ANH_VIPHAM_THOI_GIAN_HET_HAN
            ON dbo.ANH_VIPHAM (THOI_GIAN_HET_HAN) WHERE ANH_KHOA IS NOT NULL;';
    END;

    DELETE FROM dbo.SCHEMA_MIGRATIONS WHERE PHIEN_BAN = '008';

    COMMIT TRANSACTION;
    PRINT N'Rollback migration 008 thành công.';
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
