/*
  Rollback migration 010. Đưa HOCKY về (ID IDENTITY PK, MA_HK UNIQUE, TEN_HK) và CT_VIPHAM về MA_HK.
  MA_HK/TEN_HK được ghép lại từ (NAM_HOC, HOC_KY): HK<n>-<năm bắt đầu>, "Học kỳ <n> (<năm học>)".
  Không xóa dòng dữ liệu nào. Các lệnh dùng cột vừa thêm/sắp xóa chạy qua EXEC để biên dịch sau.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
GO

IF COL_LENGTH(N'dbo.HOCKY', N'NAM_HOC') IS NULL
    THROW 50013, N'HOCKY không có cột NAM_HOC: migration 010 chưa được áp dụng.', 1;

BEGIN TRY
    BEGIN TRANSACTION;

    IF COL_LENGTH(N'dbo.HOCKY', N'ID') IS NULL
        ALTER TABLE dbo.HOCKY ADD ID INT IDENTITY(1, 1) NOT NULL;
    IF COL_LENGTH(N'dbo.HOCKY', N'MA_HK') IS NULL
        ALTER TABLE dbo.HOCKY ADD MA_HK VARCHAR(20) NULL, TEN_HK NVARCHAR(100) NULL;
    IF COL_LENGTH(N'dbo.CT_VIPHAM', N'MA_HK') IS NULL
        ALTER TABLE dbo.CT_VIPHAM ADD MA_HK VARCHAR(20) NULL;

    EXEC(N'
        UPDATE dbo.HOCKY SET MA_HK = CONCAT(''HK'', HOC_KY, ''-'', LEFT(NAM_HOC, 4)),
                             TEN_HK = CONCAT(N''Học kỳ '', HOC_KY, N'' ('', NAM_HOC, N'')'');
        UPDATE cv SET cv.MA_HK = hk.MA_HK
        FROM dbo.CT_VIPHAM cv INNER JOIN dbo.HOCKY hk ON hk.NAM_HOC = cv.NAM_HOC AND hk.HOC_KY = cv.HOC_KY;
    ');

    IF OBJECT_ID(N'dbo.FK_CT_VIPHAM_HOCKY_KEP', N'F') IS NOT NULL
        ALTER TABLE dbo.CT_VIPHAM DROP CONSTRAINT FK_CT_VIPHAM_HOCKY_KEP;
    IF OBJECT_ID(N'dbo.CK_CT_VIPHAM_HOCKY_DU_CAP', N'C') IS NOT NULL
        ALTER TABLE dbo.CT_VIPHAM DROP CONSTRAINT CK_CT_VIPHAM_HOCKY_DU_CAP;
    IF EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IX_CT_VIPHAM_HOCKY' AND object_id = OBJECT_ID(N'dbo.CT_VIPHAM'))
        DROP INDEX IX_CT_VIPHAM_HOCKY ON dbo.CT_VIPHAM;
    IF COL_LENGTH(N'dbo.CT_VIPHAM', N'NAM_HOC') IS NOT NULL
        ALTER TABLE dbo.CT_VIPHAM DROP COLUMN NAM_HOC, HOC_KY;

    IF OBJECT_ID(N'dbo.PK_HOCKY', N'PK') IS NOT NULL
        ALTER TABLE dbo.HOCKY DROP CONSTRAINT PK_HOCKY;
    IF OBJECT_ID(N'dbo.CK_HOCKY_HOC_KY', N'C') IS NOT NULL
        ALTER TABLE dbo.HOCKY DROP CONSTRAINT CK_HOCKY_HOC_KY;
    IF OBJECT_ID(N'dbo.CK_HOCKY_NAM_HOC', N'C') IS NOT NULL
        ALTER TABLE dbo.HOCKY DROP CONSTRAINT CK_HOCKY_NAM_HOC;
    IF COL_LENGTH(N'dbo.HOCKY', N'NAM_HOC') IS NOT NULL
        ALTER TABLE dbo.HOCKY DROP COLUMN NAM_HOC, HOC_KY;

    EXEC(N'
        ALTER TABLE dbo.HOCKY ALTER COLUMN MA_HK VARCHAR(20) NOT NULL;
        ALTER TABLE dbo.HOCKY ALTER COLUMN TEN_HK NVARCHAR(100) NOT NULL;
    ');
    EXEC(N'
        ALTER TABLE dbo.HOCKY ADD CONSTRAINT PK_HOCKY_ID PRIMARY KEY (ID);
        ALTER TABLE dbo.HOCKY ADD CONSTRAINT UQ_HOCKY_MA_HK UNIQUE (MA_HK);
        ALTER TABLE dbo.CT_VIPHAM ADD CONSTRAINT FK_CT_VIPHAM_HOCKY
            FOREIGN KEY (MA_HK) REFERENCES dbo.HOCKY (MA_HK) ON UPDATE CASCADE;
        CREATE INDEX IX_CT_VIPHAM_MA_HK ON dbo.CT_VIPHAM (MA_HK, NGAY_VIPHAM);
    ');

    DELETE FROM dbo.SCHEMA_MIGRATIONS WHERE PHIEN_BAN = '010';

    COMMIT TRANSACTION;
    PRINT N'Đã rollback migration 010.';
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
