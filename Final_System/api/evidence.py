"""
Evidence image storage.

- Uploaded bytes are validated (signature, decodable, dimension limits) and re-encoded to JPEG,
  which drops EXIF/metadata and anything appended to the file.
- File names are generated by the server (`YYYY/MM/<uuid>.jpg`); client file names are ignored.
- Every resolve/delete checks that the final path stays inside the evidence root, so a
  corrupted or malicious storage key can never point outside it.
- Files are written atomically (temporary file + os.replace).
"""
from __future__ import annotations

import hashlib
import logging
import os
import re
import uuid
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import cv2
import numpy as np

logger = logging.getLogger(__name__)

JPEG_SIGNATURE = b"\xff\xd8\xff"
PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
MIN_DIMENSION = 16
_KEY_PATTERN = re.compile(r"^\d{4}/\d{2}/[0-9a-f]{32}\.jpg$")


class EvidenceError(ValueError):
    def __init__(self, message: str, status_code: int = 422):
        super().__init__(message)
        self.status_code = status_code


class UnsafeEvidencePath(EvidenceError):
    pass


@dataclass(frozen=True)
class StoredEvidence:
    key: str
    sha256: str
    size: int
    width: int
    height: int


def validate_and_normalize_image(data: bytes, max_bytes: int, max_dimension: int) -> tuple[bytes, int, int]:
    """Return (jpeg_bytes, width, height) or raise EvidenceError."""
    if not data:
        raise EvidenceError("Thiếu ảnh bằng chứng hoặc ảnh rỗng.")
    if len(data) > max_bytes:
        raise EvidenceError(f"Ảnh vượt quá dung lượng cho phép ({max_bytes // 1024} KB).", 413)
    if not (data.startswith(JPEG_SIGNATURE) or data.startswith(PNG_SIGNATURE)):
        raise EvidenceError("Ảnh phải ở định dạng JPEG hoặc PNG.", 415)
    image = cv2.imdecode(np.frombuffer(data, dtype=np.uint8), cv2.IMREAD_COLOR)
    if image is None:
        raise EvidenceError("Không đọc được nội dung ảnh (ảnh hỏng hoặc sai định dạng).")
    height, width = image.shape[:2]
    if width < MIN_DIMENSION or height < MIN_DIMENSION:
        raise EvidenceError(f"Ảnh quá nhỏ (tối thiểu {MIN_DIMENSION}x{MIN_DIMENSION} pixel).")
    if width > max_dimension or height > max_dimension:
        raise EvidenceError(f"Ảnh quá lớn (tối đa {max_dimension}x{max_dimension} pixel).")
    ok, encoded = cv2.imencode(".jpg", image, [int(cv2.IMWRITE_JPEG_QUALITY), 90])
    if not ok:
        raise EvidenceError("Không thể chuẩn hóa ảnh bằng chứng.")
    return encoded.tobytes(), width, height


class EvidenceStorage:
    def __init__(self, root: Path):
        self.root = Path(root).resolve()

    def ensure_root(self) -> None:
        self.root.mkdir(parents=True, exist_ok=True)

    def resolve(self, key: str) -> Path:
        """Map a storage key to an absolute path inside the root or raise UnsafeEvidencePath."""
        if not isinstance(key, str) or not _KEY_PATTERN.fullmatch(key.replace("\\", "/")):
            raise UnsafeEvidencePath("Khóa lưu trữ ảnh không hợp lệ.")
        candidate = (self.root / key).resolve()
        try:
            candidate.relative_to(self.root)
        except ValueError as exc:
            raise UnsafeEvidencePath("Đường dẫn ảnh nằm ngoài thư mục lưu trữ.") from exc
        return candidate

    def save(self, jpeg_bytes: bytes, width: int, height: int, when: datetime) -> StoredEvidence:
        self.ensure_root()
        key = f"{when:%Y}/{when:%m}/{uuid.uuid4().hex}.jpg"
        target = self.resolve(key)
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_suffix(".tmp")
        with open(temporary, "wb") as handle:
            handle.write(jpeg_bytes)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, target)
        return StoredEvidence(key=key, sha256=hashlib.sha256(jpeg_bytes).hexdigest(), size=len(jpeg_bytes),
                              width=width, height=height)

    def exists(self, key: str) -> bool:
        try:
            return self.resolve(key).is_file()
        except UnsafeEvidencePath:
            return False

    def delete(self, key: str) -> bool:
        """Delete a stored file. Returns False if it was already missing."""
        path = self.resolve(key)
        if path.is_symlink():
            raise UnsafeEvidencePath("Không xóa liên kết tượng trưng trong thư mục ảnh.")
        try:
            path.unlink()
        except FileNotFoundError:
            return False
        return True
